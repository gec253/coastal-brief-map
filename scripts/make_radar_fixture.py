"""Generate the SYNTHETIC radar fixture for the private /radar viewer's test mode.

Not real radar: a few smooth rain cells drifting north-east across coastal NC, drawn as 256 px Web Mercator
PNG tiles at zoom 7 in WeatherAPI's tile/legend shape, each tile watermarked "TEST DATA". Times are a fixed
past window (Sun Mar 8, 2026, 05:55-07:55 UTC observed, which crosses the EST->EDT switch at 07:00 UTC, plus
08:00-08:55 UTC "nowcast") so they can never be mistaken for current radar.
Run: python3 scripts/make_radar_fixture.py   (needs Pillow; output is committed under tests/fixtures/radar/)"""
import json, math, datetime as dt, pathlib
from PIL import Image, ImageDraw, ImageFont
OUT = pathlib.Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "radar"
Z = 7
LEGEND = [(0.1, "#9be1ff"), (0.5, "#4fc3f7"), (1, "#1e88e5"), (2, "#2e7d32"), (4, "#66bb6a"), (8, "#fdd835"), (16, "#fb8c00"), (32, "#e53935"), (64, "#ad1457")]

def tile_xy(lat, lon):
    n = 2 ** Z; x = (lon + 180) / 360 * n
    y = (1 - math.asinh(math.tan(math.radians(lat))) / math.pi) / 2 * n
    return x, y

def lonlat(px, py):
    n = 2 ** Z * 256; lon = px / n * 360 - 180
    lat = math.degrees(math.atan(math.sinh(math.pi * (1 - 2 * py / n)))); return lat, lon

def rate(lat, lon, k):
    # three cells moving ENE ~ 0.03°/frame, growing then decaying; a weaker trailing band
    r = 0.0
    for (la0, lo0, amp, sz, ph) in ((34.5, -78.0, 40, 0.16, 0.0), (35.2, -77.4, 24, 0.22, 1.3), (34.0, -76.9, 16, 0.3, 2.1), (35.6, -76.6, 9, 0.12, 0.7)):
        la, lo = la0 + 0.012 * k, lo0 + 0.035 * k
        a = amp * (0.6 + 0.4 * math.sin(ph + k / 6))
        d2 = ((lat - la) / sz) ** 2 + ((lon - lo) / (sz * 1.6)) ** 2
        r += a * math.exp(-d2)
    band = 1.2 * math.exp(-(((lat - 35.0) - 0.8 * (lon + 76.5 - 0.03 * k)) / 0.12) ** 2) * math.exp(-((lon + 76.5 - 0.03 * k) / 1.0) ** 2)
    return r + band

def color(v):
    c = None
    for lo, hexc in LEGEND:
        if v >= lo: c = hexc
    return c

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for p in OUT.glob("*.png"): p.unlink()
    x0, y0 = tile_xy(37.6, -80.2); x1, y1 = tile_xy(32.4, -72.8)
    xs, ys = range(int(x0), int(x1) + 1), range(int(y0), int(y1) + 1)
    base = dt.datetime(2026, 3, 8, 5, 55, tzinfo=dt.timezone.utc)
    frames = [(base + dt.timedelta(minutes=5 * i), "observed") for i in range(25)] + [(base + dt.timedelta(minutes=125 + 5 * i), "nowcast") for i in range(12)]
    pal = [tuple(int(h[i:i + 2], 16) for i in (1, 3, 5)) for _, h in LEGEND]
    try: font = ImageFont.truetype("DejaVuSans-Bold.ttf", 22)
    except OSError: font = ImageFont.load_default()
    S = 128   # compute the field on a 64x64 grid per tile, upsample smoothly
    for k, (t, typ) in enumerate(frames):
        code = t.strftime("%Y%m%d%H%M")
        for tx in xs:
            for ty in ys:
                small = Image.new("RGBA", (S, S), (0, 0, 0, 0)); px = small.load()
                for j in range(S):
                    for i in range(S):
                        la, lo = lonlat(tx * 256 + (i + 0.5) * 256 / S, ty * 256 + (j + 0.5) * 256 / S)
                        c = color(rate(la, lo, k))
                        if c: px[i, j] = tuple(int(c[q:q + 2], 16) for q in (1, 3, 5)) + (200,)
                im = small.resize((256, 256), Image.NEAREST)
                d = ImageDraw.Draw(im)
                d.text((128, 128), "TEST DATA", fill=(120, 0, 120, 110), font=font, anchor="mm")
                im = im.quantize(colors=16, method=Image.Quantize.FASTOCTREE)
                im.save(OUT / ("%s_%d_%d_%d.png" % (code, Z, tx, ty)), optimize=True)
    meta = {
        "fixture": True,
        "label": "TEST DATA — not current radar",
        "source": "Synthetic test pattern generated by scripts/make_radar_fixture.py (not radar data, not NOAA or WeatherAPI imagery).",
        "frames": [{"time": t.strftime("%Y%m%d%H%M"), "time_epoch": int(t.timestamp()), "type": typ} for t, typ in frames],
        "legend": [{"from_mm_h": a, "color": c} for a, c in LEGEND],
        "zoom": Z, "tiles_x": [min(xs), max(xs)], "tiles_y": [min(ys), max(ys)],
    }
    (OUT / "fixture.json").write_text(json.dumps(meta, indent=1, ensure_ascii=False))
    print(len(frames), "frames", len(xs) * len(ys), "tiles each")

if __name__ == "__main__":
    main()
